/**
 * Obtient automatiquement l'emoji drapeau à partir du nom du pays, de son code ou d'une chaîne
 */
export function getCountryFlag(countryName?: string | null): string {
  if (!countryName) return "🌍";
  const clean = countryName.toLowerCase().trim();

  // Si c'est déjà un emoji de drapeau (caractères régionaux ou emoji unicode)
  if (/[\uD83C][\uDDE6-\uDDFF]{2}/.test(countryName) || countryName.length <= 4 && /[\uD800-\uDBFF][\uDC00-\uDFFF]/.test(countryName)) {
    return countryName;
  }

  // Correspondance exacte
  if (COUNTRY_FLAGS[clean]) {
    return COUNTRY_FLAGS[clean];
  }

  // Correspondance partielle (ex: "Visa Russie Business" -> Russie)
  for (const [key, flag] of Object.entries(COUNTRY_FLAGS)) {
    if (key.length >= 4 && clean.includes(key)) {
      return flag;
    }
  }

  return "🌍";
}
